CREATE SEQUENCE numero_nota_fiscal START 1;

CREATE TABLE nota_fiscal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id VARCHAR(60) NOT NULL,
    transacao_id VARCHAR(100) NOT NULL,
    numero BIGINT NOT NULL,
    serie INTEGER NOT NULL,
    chave_acesso VARCHAR(44) NOT NULL UNIQUE,
    valor_total NUMERIC(10, 2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    protocolo VARCHAR(20),
    codigo_retorno VARCHAR(10),
    motivo VARCHAR(255),
    criado_em TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP NOT NULL,
    CONSTRAINT uk_nota_fiscal_pedido_transacao UNIQUE (pedido_id, transacao_id)
);

CREATE TABLE outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topico VARCHAR(100) NOT NULL,
    chave VARCHAR(60) NOT NULL,
    payload TEXT NOT NULL,
    criado_em TIMESTAMP NOT NULL,
    enviado_em TIMESTAMP
);

CREATE INDEX idx_outbox_pendentes ON outbox (id) WHERE enviado_em IS NULL;
