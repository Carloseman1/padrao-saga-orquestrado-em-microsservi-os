CREATE TABLE cartao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    numero_criptografado VARCHAR(255) NOT NULL,
    ultimos_quatro VARCHAR(4) NOT NULL,
    cvv_criptografado VARCHAR(255) NOT NULL,
    nome_titular VARCHAR(120) NOT NULL,
    validade_mes INTEGER NOT NULL,
    validade_ano INTEGER NOT NULL,
    criado_em TIMESTAMP NOT NULL
);

CREATE INDEX idx_cartao_usuario ON cartao (usuario_id);
