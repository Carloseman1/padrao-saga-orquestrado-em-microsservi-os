CREATE TABLE baixa_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id VARCHAR(60) NOT NULL,
    transacao_id VARCHAR(100) NOT NULL,
    sucesso BOOLEAN NOT NULL,
    criado_em TIMESTAMP NOT NULL,
    CONSTRAINT uk_baixa_estoque_pedido_transacao UNIQUE (pedido_id, transacao_id)
);

INSERT INTO baixa_estoque (pedido_id, transacao_id, sucesso, criado_em)
SELECT pedido_id, transacao_id, TRUE, MIN(criado_em)
FROM movimentacao_estoque
GROUP BY pedido_id, transacao_id;
